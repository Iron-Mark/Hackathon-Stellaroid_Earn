import type { Metadata, Viewport } from "next";
import { Exo_2, Orbitron } from "next/font/google";
import { cookies } from "next/headers";
import { Analytics } from "@vercel/analytics/next";
import { DeferredToastProvider } from "@/components/layout/deferred-toast-provider";
import { ErrorReporter } from "@/components/telemetry/error-reporter";
import { JsonLd } from "@/components/ui/json-ld";
import { ScrollToTop } from "@/components/layout/scroll-to-top";
import { ServiceWorkerRegistration } from "@/components/pwa/service-worker-registration";
import { APPLE_SPLASH } from "@/lib/apple-splash.generated";
import "../styles/globals.css";
import {
  SITE_AUTHOR_LINKEDIN,
  SITE_AUTHOR_NAME,
  SITE_AUTHOR_URL,
  SITE_CANONICAL_URL,
  SITE_DESCRIPTION,
  SITE_KEYWORDS,
  SITE_LOGO_URL,
  SITE_NAME,
  SITE_ORG_SAME_AS,
} from "@/lib/seo";

// Self-hosted brand faces (globals.css declared these families for months but
// nothing ever loaded them — the site silently rendered in system fonts).
// display:swap + next/font's size-adjusted fallback keep CLS at ~0.
const orbitron = Orbitron({
  subsets: ["latin"],
  display: "swap",
  variable: "--font-orbitron",
  // Not preloaded: the LCP hero text renders in Exo 2 — keeping this 41 KB
  // display face out of the pre-FCP critical window buys first paint time;
  // the size-adjusted fallback bounds the later swap shift.
  preload: false,
});
const exo2 = Exo_2({
  subsets: ["latin"],
  display: "swap",
  variable: "--font-exo2",
});

const BASE_URL = SITE_CANONICAL_URL;
const ENABLE_VERCEL_ANALYTICS =
  Boolean(process.env.VERCEL) || process.env.NEXT_PUBLIC_ENABLE_VERCEL_ANALYTICS === "1";

export const viewport: Viewport = {
  // Match --color-bg and the manifest theme_color so browser chrome and the
  // installed-app title bar blend with the dark UI.
  themeColor: "#0F172A",
  // Required for env(safe-area-inset-*) so the bottom nav clears the iOS home indicator
  viewportFit: "cover",
};

