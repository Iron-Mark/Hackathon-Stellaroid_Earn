const authorProfileJsonLd = {
  "@context": "https://schema.org",
  "@type": "Person",
  name: SITE_AUTHOR_NAME,
  url: SITE_AUTHOR_URL,
  sameAs: [SITE_AUTHOR_LINKEDIN, SITE_AUTHOR_URL],
};

const webSiteJsonLd = {
  "@context": "https://schema.org",
  "@type": "WebSite",
  name: SITE_NAME,
  url: BASE_URL,
  description: SITE_DESCRIPTION,
  publisher: { "@type": "Organization", name: SITE_NAME, url: BASE_URL },
  // Proof lookup by hash — enables the sitelinks search box.
  potentialAction: {
    "@type": "SearchAction",
    target: {
      "@type": "EntryPoint",
      urlTemplate: `${BASE_URL}/proof/{hash}`,
    },
    "query-input": "required name=hash",
  },
};

export default async function RootLayout({ children }: { children: React.ReactNode }) {
  const cookieStore = await cookies();
  const lang = cookieStore.get("stellaroid:locale")?.value === "tl" ? "tl" : "en";

  return (
    <html lang={lang} className={`${orbitron.variable} ${exo2.variable} font-sans`}>
      <body suppressHydrationWarning>
        {webAppJsonLd.map((schema, i) => (
          <JsonLd key={i} data={schema} />
        ))}
        <JsonLd data={webSiteJsonLd} />
        <JsonLd data={authorProfileJsonLd} />
        {children}
        <ScrollToTop />
        {ENABLE_VERCEL_ANALYTICS ? <Analytics /> : null}
        <DeferredToastProvider />
        <ServiceWorkerRegistration />
        <ErrorReporter />
      </body>
    </html>
  );
}
